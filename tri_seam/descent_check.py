#!/usr/bin/env python3
"""Independent 3-isogeny descent check of the diagonal-cubic box (see PREREG_descent.md).

    python3 -m venv .venv-eclib && .venv-eclib/bin/pip install passagemath-eclib
    .venv-eclib/bin/python descent_check.py [--input cubic_faces_results.json] [--limit N] [--workers 32]

Rank and saturated generators of E': y^2 = x^3 + 16 D^2 come from Cremona's mwrank (eclib), not from PARI.
The descent map, cube-class arithmetic and membership test are written here from scratch with exact integers.
Writes descent_results.json next to this file.
"""
import argparse
import itertools
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
DESCENT_ONLY = ([1, 25, 29], [19, 25, 29])          # solvable per the record, points beyond the search bound
CURVE_TIMEOUT = 1800


# ------------------------------------------------------------------ exact cube-class arithmetic
def icbrt(n):
    """Floor cube root of a non-negative integer."""
    if n < 2:
        return n
    x = 1 << ((n.bit_length() + 2) // 3)
    while True:
        y = (2 * x + n // (x * x)) // 3
        if y >= x:
            break
        x = y
    while x ** 3 > n:
        x -= 1
    while (x + 1) ** 3 <= n:
        x += 1
    return x


def is_cube(q):
    """A non-zero rational is a cube iff its reduced numerator and denominator are; -1 is a cube."""
    q = Fraction(q)
    if q == 0:
        return False
    n, d = abs(q.numerator), q.denominator
    return icbrt(n) ** 3 == n and icbrt(d) ** 3 == d


def in_image(m, D, deltas):
    """Is m in the subgroup of Q*/Q*^3 generated by [D] (torsion) and the delta images of the generators?"""
    basis = [Fraction(D)] + list(deltas)
    for e in itertools.product(range(3), repeat=len(basis)):
        q = Fraction(m)
        for b, k in zip(basis, e):
            if k:
                q *= b ** k
        if is_cube(q):
            return True, list(e)
    return False, None


def delta(pt, D):
    """delta(xi, eta) = [eta - 4D] for a non-torsion point (the record's convention, section 1)."""
    xi, eta = pt
    if xi == 0:
        raise ValueError("torsion point passed as generator")
    return eta - 4 * D


# ------------------------------------------------------------------ one curve (runs in a child process)
def to_affine(g, k):
    """mwrank returns projective [X, Y, Z]; accept the convention that lands on y^2 = x^3 + k."""
    g = [Fraction(int(v)) if float(v).is_integer() else Fraction(str(v)) for v in g]
    cands = [(g[0], g[1])] if len(g) == 2 else [(g[0] / g[2], g[1] / g[2]), (g[0] / g[2] ** 2, g[1] / g[2] ** 3)]
    for x, y in cands:
        if y * y == x ** 3 + k:
            return x, y
    raise ValueError(f"generator {g} not on y^2 = x^3 + {k}")


def one_curve(D):
    from sage.libs.eclib.interface import mwrank_EllipticCurve
    k = 16 * D * D
    t0 = time.time()
    E = mwrank_EllipticCurve([0, 0, 0, 0, k], verbose=False)
    rank = int(E.rank())
    certain = bool(E.certain())
    E.saturate(-1)                                   # saturate at all primes (automatic bound)
    pts = [to_affine(list(g), k) for g in E.gens()]
    return {"D": D, "rank": rank, "certain": certain, "n_gens": len(pts),
            "gens": [[str(x), str(y)] for x, y in pts], "secs": round(time.time() - t0, 2)}


def run_curve(D):
    try:
        p = subprocess.run([sys.executable, os.path.abspath(__file__), "--curve", str(D)],
                           capture_output=True, text=True, timeout=CURVE_TIMEOUT)
        if p.returncode:
            return {"D": D, "error": p.stderr.strip()[-500:]}
        return json.loads(p.stdout.strip().splitlines()[-1])
    except subprocess.TimeoutExpired:
        return {"D": D, "error": f"timeout {CURVE_TIMEOUT}s"}


# ------------------------------------------------------------------ main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", default=os.path.join(HERE, "cubic_faces_results.json"))
    ap.add_argument("--limit", type=int, default=0, help="test on the first N admissible cubics only")
    ap.add_argument("--workers", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--curve", type=int, help=argparse.SUPPRESS)
    a = ap.parse_args()
    if a.curve is not None:
        print(json.dumps(one_curve(a.curve)))
        return

    t0 = time.time()
    rows = [r for r in json.load(open(a.input))["rows"] if r["A"] == "PASS"]
    if a.limit:
        rows = rows[:a.limit]
    Ds = sorted({r["abc"][0] * r["abc"][1] * r["abc"][2] for r in rows})
    print(f"{len(rows)} admissible cubics, {len(Ds)} companion curves, {a.workers} workers", flush=True)
    with ThreadPoolExecutor(a.workers) as ex:
        curves = {c["D"]: c for c in ex.map(run_curve, Ds)}
    print(f"[{time.time() - t0:6.1f}s] mwrank done", flush=True)

    out = []
    for r in rows:
        aa, b, c = r["abc"]
        D = aa * b * c
        cv = curves[D]
        solvable_record = r.get("point") is not None or r["abc"] in DESCENT_ONLY
        rec = {"abc": r["abc"], "D": D, "record": "solvable" if solvable_record else "obstructed"}
        decided = "error" not in cv and cv["certain"] and cv["n_gens"] == cv["rank"]
        if not decided:
            rec.update(descent="UNRESOLVED", why=cv.get("error") or f"certain={cv['certain']} rank={cv['rank']} gens={cv['n_gens']}")
        else:
            deltas = [delta((Fraction(x), Fraction(y)), D) for x, y in cv["gens"]]
            hit, expo = in_image(Fraction(b, c), D, deltas)
            rec.update(descent="solvable" if hit else "obstructed", rank=cv["rank"], exponents=expo)
        rec["agrees"] = rec["descent"] == rec["record"] if rec["descent"] != "UNRESOLVED" else None
        # Tri-seam faces with the descent witness added
        pt = r.get("point") is not None
        co_g = "PASS" if (pt or rec["descent"] == "solvable") else ("FAIL" if rec["descent"] == "obstructed" else "UNRESOLVED")
        rec["faces"] = {"A": "PASS", "L": "PASS" if pt else "UNRESOLVED", "Co_global": co_g}
        rec["tri"] = "FAIL" if co_g == "FAIL" else ("PASS" if pt else "UNRESOLVED")
        out.append(rec)

    def n(f):
        return sum(1 for x in out if f(x))

    sol = [x for x in out if x["record"] == "solvable"]
    obs = [x for x in out if x["record"] == "obstructed"]
    summary = {
        "admissible": len(out), "curves": len(Ds),
        "curves_undecided": [c["D"] for c in curves.values() if "error" in c or not c["certain"] or c["n_gens"] != c["rank"]],
        "D1_solvable_in_image": f"{n(lambda x: x['record'] == 'solvable' and x['descent'] == 'solvable')}/{len(sol)}",
        "D1_solvable_undecided": n(lambda x: x["record"] == "solvable" and x["descent"] == "UNRESOLVED"),
        "D2_obstructed_confirmed": f"{n(lambda x: x['record'] == 'obstructed' and x['descent'] == 'obstructed')}/{len(obs)}",
        "D2_obstructed_undecided": n(lambda x: x["record"] == "obstructed" and x["descent"] == "UNRESOLVED"),
        "disagreements": [x["abc"] for x in out if x["agrees"] is False],
        "D3_obstructed_rank0": n(lambda x: x["record"] == "obstructed" and x.get("rank") == 0),
        "D3_obstructed_rank_pos": n(lambda x: x["record"] == "obstructed" and (x.get("rank") or 0) > 0),
        "D4_decided_share": round(n(lambda x: x["descent"] != "UNRESOLVED") / len(out), 4),
        "D5_tri_verdicts": {v: n(lambda x, v=v: x["tri"] == v) for v in ("PASS", "FAIL", "UNRESOLVED")},
        "max_rank": max((c.get("rank", 0) for c in curves.values()), default=0),
        "slowest_curve_secs": max((c.get("secs", 0) for c in curves.values()), default=0),
        "secs": round(time.time() - t0, 1),
    }
    try:
        from importlib.metadata import version
        summary["eclib_backend"] = "passagemath-eclib " + version("passagemath-eclib")
    except Exception:                                           # noqa: BLE001
        summary["eclib_backend"] = "unknown"
    json.dump({"summary": summary, "curves": curves, "cubics": out},
              open(os.path.join(HERE, "descent_results.json"), "w"), indent=1, default=str)
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
